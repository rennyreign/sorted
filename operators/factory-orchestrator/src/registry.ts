// ─────────────────────────────────────────────────────────────
// Asset Registry — deterministic supplied-asset processing
//
// Reads artifacts/input-contract.json and turns supplied image/font
// files into production assets under public/images/:
//   - originals are preserved untouched in input/
//   - raster images → WebP q82, resized to max 1600px wide,
//     never upscaled; width/height/format read from decoding
//   - SVG copied unchanged
//   - other permitted files (fonts, md/txt, json) copied unchanged
//   - safe unique output filenames derived from asset_id
//   - refuses arbitrary filename collisions — overwrite is allowed
//     only when the existing file was previously generated by this
//     registry for the same asset
//
// Uses the repo's installed sharp via createRequire — no new deps.
// Writes artifacts/asset-registry.json in the existing
// AssetRegistryArtifact shape plus source sha/provenance.
// ─────────────────────────────────────────────────────────────

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';
import type { InputContract } from './pack-intake.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const RASTER_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif']);
const MAX_WIDTH = 1600;
const WEBP_QUALITY = 82;

// sharp lives at the sorted repo root — resolve relative to this file
// (dist/registry.js → operators/factory-orchestrator → sorted).
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Sharp = (input: string) => any;

function loadSharp(): Sharp {
  const sortedRoot = path.resolve(__dirname, '..', '..', '..');
  const req = createRequire(path.join(sortedRoot, 'package.json'));
  return req('sharp') as Sharp;
}

export interface RegisteredAsset {
  asset_id: string;
  production_path: string;
  file_path: string;
  format: string;
  variants: { original?: string };
  width?: number;
  height?: number;
  source_sha256: string | null;
  provenance: 'supplied' | 'unresolved';
  required: boolean;
  notes?: string;
}

export interface RegisterResult {
  registryPath: string;
  assets: RegisteredAsset[];
  warnings: string[];
}

function safeFileStem(assetId: string): string {
  const stem = assetId.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  if (!stem) throw new Error(`Asset id '${assetId}' produces no safe filename`);
  return stem;
}

export async function registerAssets(buildDir: string): Promise<RegisterResult> {
  const root = path.resolve(buildDir);
  const contractPath = path.join(root, 'artifacts', 'input-contract.json');
  if (!fs.existsSync(contractPath)) {
    throw new Error(`No input contract at ${contractPath} — run init-pack first`);
  }
  const contract = JSON.parse(fs.readFileSync(contractPath, 'utf-8')) as InputContract;

  const sharp = loadSharp();
  const imagesOut = path.join(root, 'public', 'images');
  fs.mkdirSync(imagesOut, { recursive: true });

  const warnings: string[] = [...(contract.warnings ?? [])];
  const assets: RegisteredAsset[] = [];
  const usedNames = new Map<string, string>(); // output filename → asset_id

  // Prior registry outputs may be regenerated in place — anything else
  // occupying a target name is a hard collision.
  const registryPath = path.join(root, 'artifacts', 'asset-registry.json');
  const priorTargets = new Set<string>();
  if (fs.existsSync(registryPath)) {
    const prior = JSON.parse(fs.readFileSync(registryPath, 'utf-8')) as {
      assets?: Array<{ file_path?: string; asset_id?: string }>;
    };
    for (const a of prior.assets ?? []) {
      if (a.file_path) priorTargets.add(path.resolve(root, a.file_path));
    }
  }

  for (const declared of contract.assets ?? []) {
    if (declared.provenance === 'unresolved') {
      if (declared.required) {
        throw new Error(`Required asset '${declared.asset_id}' is unresolved — cannot build registry`);
      }
      warnings.push(`optional asset '${declared.asset_id}' remains unresolved`);
      continue;
    }

    const srcAbs = path.resolve(root, declared.source_path);
    if (!srcAbs.startsWith(root + path.sep)) {
      throw new Error(`Asset '${declared.asset_id}' source escapes build dir: ${declared.source_path}`);
    }
    if (!fs.existsSync(srcAbs)) {
      throw new Error(`Asset '${declared.asset_id}' source file missing: ${declared.source_path}`);
    }

    const actualSha = crypto.createHash('sha256').update(fs.readFileSync(srcAbs)).digest('hex');
    if (declared.sha256 && actualSha !== declared.sha256) {
      throw new Error(`Asset '${declared.asset_id}' source hash mismatch: ${declared.source_path}`);
    }

    const ext = path.extname(srcAbs).toLowerCase();
    const stem = safeFileStem(declared.asset_id);
    const isRaster = RASTER_EXTENSIONS.has(ext);
    const isSvg = ext === '.svg';
    const outName = isRaster ? `${stem}.webp` : `${stem}${ext || '.bin'}`;
    const destAbs = path.join(imagesOut, outName);

    const owner = usedNames.get(outName);
    if (owner && owner !== declared.asset_id) {
      throw new Error(`Output filename collision: '${outName}' claimed by both '${owner}' and '${declared.asset_id}'`);
    }
    usedNames.set(outName, declared.asset_id);

    if (fs.existsSync(destAbs) && !priorTargets.has(destAbs)) {
      throw new Error(`Refusing to overwrite existing file not produced by this registry: public/images/${outName}`);
    }

    let width: number | undefined;
    let height: number | undefined;
    let format: string;

    if (isSvg) {
      fs.copyFileSync(srcAbs, destAbs);
      format = 'svg';
    } else if (isRaster) {
      // Decode for real dimensions — corrupt images throw here.
      const meta = await sharp(srcAbs).metadata();
      width = meta.width;
      height = meta.height;
      const pipeline = sharp(srcAbs);
      if (width && width > MAX_WIDTH) {
        pipeline.resize({ width: MAX_WIDTH, withoutEnlargement: true });
      }
      await pipeline.webp({ quality: WEBP_QUALITY }).toFile(destAbs);
      format = 'webp';
    } else {
      // fonts, md/txt, json — copied unchanged
      fs.copyFileSync(srcAbs, destAbs);
      format = ext.replace('.', '') || 'file';
    }

    assets.push({
      asset_id: declared.asset_id,
      production_path: `/images/${outName}`,
      file_path: path.relative(root, destAbs).split(path.sep).join('/'),
      format,
      variants: { original: declared.source_path },
      width,
      height,
      source_sha256: actualSha,
      provenance: 'supplied',
      required: declared.required,
      notes: `source ${declared.source_path}`,
    });
  }

  // Validate: every required asset must now have a produced file
  const missing = assets.filter(a => a.required && !fs.existsSync(path.join(root, a.file_path)));
  if (missing.length > 0) {
    throw new Error(`Registry production missing files for: ${missing.map(a => a.asset_id).join(', ')}`);
  }

  const artifact = {
    generated_at: new Date().toISOString(),
    assets,
  };
  fs.mkdirSync(path.dirname(registryPath), { recursive: true });
  const tmp = `${registryPath}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, JSON.stringify(artifact, null, 2), 'utf-8');
  fs.renameSync(tmp, registryPath);

  return { registryPath, assets, warnings };
}
